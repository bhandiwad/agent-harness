"""Synchronous/asynchronous service SDK. Reads may resume; writes never retry implicitly."""

import asyncio
import re
import time
from uuid import uuid4

import httpx2

from pandita_agent.agent.native_tools import valid_path
from pandita_agent.agent.sdk_types import (
    ACTIVE,
    PAUSE_EVENTS,
    Event,
    EventDecoder,
    IncompleteStream,
    PreparedCommand,
    Session,
    StreamClosed,
    TransportError,
    WaitTimeout,
    api_path,
    check_status,
    session_id,
)
from pandita_agent.bindings import ModelBinding


def buffered(response, raw):
    # iter_bytes has already decoded transfer/content encoding.
    headers = {
        k: v
        for k, v in response.headers.items()
        if k.lower() not in {"content-encoding", "content-length", "transfer-encoding"}
    }
    return httpx2.Response(
        response.status_code,
        headers=headers,
        content=bytes(raw),
        request=response.request,
    )


class Commands:
    def _configure(self, endpoint, token, timeout):
        ModelBinding.explicit_endpoint(endpoint)
        if not 0 < timeout <= 120:
            raise ValueError("Request timeout must be between zero and 120 seconds.")
        self.token, self.timeout = token, timeout

    def _headers(self):
        token = self.token() if callable(self.token) else self.token
        if (
            not isinstance(token, str)
            or not token
            or len(token) > 16384
            or any(c in token for c in ("\r", "\n"))
        ):
            raise ValueError("Supply a valid short-lived bearer token.")
        return {"Authorization": "Bearer " + token}

    @staticmethod
    def _agent_path(agent_id):
        if not isinstance(agent_id, str) or not re.fullmatch(
            r"[a-zA-Z0-9_-][a-zA-Z0-9_.-]{0,127}", agent_id
        ):
            raise ValueError("Invalid agent identifier.")
        return "/v1/agents/" + agent_id + "/capabilities"

    def create(self, agent_id, title="New conversation"):
        return PreparedCommand(
            "/v1/sessions",
            {"command_id": str(uuid4()), "agent_id": agent_id, "title": title},
        )

    def prepare(self, session, operation, **fields):
        if operation not in {
            "turns",
            "memory",
            "files",
            "decisions",
            "cancel",
            "reconcile",
        }:
            raise ValueError("Unsupported session command.")
        if {"command_id", "expected_revision"} & fields.keys():
            raise ValueError("Command metadata is generated by the client.")
        value = (
            session.model_dump(mode="json") if isinstance(session, Session) else session
        )
        return PreparedCommand(
            f"/v1/sessions/{session_id(value['id'])}/{operation}",
            {
                "command_id": str(uuid4()),
                "expected_revision": value["revision"],
                **fields,
            },
        )

    def prepare_turn(self, session, text):
        return self.prepare(session, "turns", text=text)

    def prepare_cancel(self, session):
        return self.prepare(session, "cancel")

    def prepare_upload(self, session, path, content, expected_digest=None):
        valid_path(path)
        return self.prepare(
            session,
            "files",
            path=path,
            content=content,
            expected_digest=expected_digest,
        )

    def prepare_decision(self, session, *, approve, reason):
        state = session.state if isinstance(session, Session) else session["state"]
        return self.prepare(
            session,
            "decisions",
            action_digest=state["run"]["pending"]["digest"],
            approve=approve,
            reason=reason,
        )

    @staticmethod
    def _stream_options(after, reconnects, timeout):
        if (
            type(after) is not int
            or after < 0
            or type(reconnects) is not int
            or not 0 <= reconnects <= 20
            or not 0 < timeout <= 3600
        ):
            raise ValueError("Use bounded stream options.")


class Client(Commands):
    def __init__(self, endpoint, token, *, timeout=30, transport=None):
        self._configure(endpoint, token, timeout)
        self.http = httpx2.Client(
            base_url=endpoint.rstrip("/"),
            timeout=timeout,
            trust_env=False,
            follow_redirects=False,
            transport=transport,
        )

    def __enter__(self):
        return self

    def __exit__(self, *args):
        self.close()

    def close(self):
        self.http.close()

    def _request(self, method, path, *, command=None, **kwargs):
        try:
            with self.http.stream(
                method, api_path(path), headers=self._headers(), **kwargs
            ) as response:
                check_status(response)
                raw = bytearray()
                for chunk in response.iter_bytes():
                    raw.extend(chunk)
                    if len(raw) > 4194304:
                        raise ValueError("API response exceeded its bound.")
                return buffered(response, raw)
        except httpx2.HTTPError as exc:
            raise TransportError(command) from exc

    def get(self, path):
        return self._request("GET", path).json()

    def execute(self, command):
        return self._request(
            "POST", command.path, command=command, json=command.body
        ).json()

    def submit(self, command):
        return Session.model_validate(self.execute(command))

    def create_session(self, agent_id, title="New conversation"):
        return self.submit(self.create(agent_id, title))

    def session(self, identifier):
        return Session.model_validate(
            self.get("/v1/sessions/" + session_id(identifier))
        )

    def agents(self):
        return self.get("/v1/agents")["agents"]

    def capabilities(self, agent_id):
        return self.get(self._agent_path(agent_id))

    def events(self, identifier, after=0):
        return [
            Event.model_validate(value)
            for value in self._request(
                "GET",
                "/v1/sessions/" + session_id(identifier) + "/events",
                params={"after": after},
            ).json()["events"]
        ]

    def download(self, identifier, path):
        valid_path(path)
        return self._request(
            "GET", f"/v1/sessions/{session_id(identifier)}/files/{path}"
        ).content

    def _snapshot(self, identifier, end, cursor=None):
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise WaitTimeout(identifier, cursor)
        return Session.model_validate(
            self._request(
                "GET",
                "/v1/sessions/" + session_id(identifier),
                timeout=min(self.timeout, remaining),
            ).json()
        )

    def wait(self, identifier, *, timeout=300, poll_interval=0.5):
        if not 0 < timeout <= 3600 or not 0 < poll_interval <= 10:
            raise ValueError("Use bounded wait options.")
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            row = Session.model_validate(
                self._request(
                    "GET",
                    "/v1/sessions/" + session_id(identifier),
                    timeout=max(0.001, min(self.timeout, end - time.monotonic())),
                ).json()
            )
            if row.status not in ACTIVE:
                return row
            time.sleep(min(poll_interval, max(0, end - time.monotonic())))
        raise WaitTimeout(identifier)

    def stream(
        self, identifier, *, after=0, reconnects=3, timeout=300, stop_on_pause=True
    ):
        self._stream_options(after, reconnects, timeout)
        cursor = after
        end = time.monotonic() + timeout
        pause_at = None
        if stop_on_pause:
            row = self._snapshot(identifier, end, cursor)
            pause_at = row.revision if row.status not in ACTIVE else None
            if pause_at is not None and cursor >= pause_at:
                return
        for attempt in range(reconnects + 1):
            if time.monotonic() >= end:
                raise WaitTimeout(identifier, cursor)
            decoder = EventDecoder()
            try:
                with self.http.stream(
                    "GET",
                    "/v1/sessions/" + session_id(identifier) + "/stream",
                    params={"after": cursor},
                    headers=self._headers(),
                    timeout=min(65, end - time.monotonic()),
                ) as response:
                    check_status(response)
                    if not response.headers.get("content-type", "").startswith(
                        "text/event-stream"
                    ):
                        raise ValueError("Expected an event stream.")
                    for chunk in response.iter_bytes():
                        if time.monotonic() >= end:
                            raise WaitTimeout(identifier, cursor)
                        for kind, data in decoder.feed(chunk):
                            if kind == "access.closed":
                                raise StreamClosed(
                                    cursor,
                                    "Access changed or expired; refresh credentials before resuming.",
                                )
                            event = Event.model_validate(data)
                            if kind != event.kind:
                                raise ValueError("Event type mismatch.")
                            if event.revision <= cursor:
                                continue
                            cursor = event.revision
                            yield event
                            if stop_on_pause and event.kind in PAUSE_EVENTS:
                                row = self._snapshot(identifier, end, cursor)
                                pause_at = (
                                    row.revision if row.status not in ACTIVE else None
                                )
                            if pause_at is not None and cursor >= pause_at:
                                return
                    decoder.finish()
            except (httpx2.HTTPError, IncompleteStream):
                pass
            if stop_on_pause:
                row = self._snapshot(identifier, end, cursor)
                if row.status not in ACTIVE and cursor >= row.revision:
                    return
            if attempt < reconnects:
                time.sleep(min(0.1 * (attempt + 1), max(0, end - time.monotonic())))
        raise StreamClosed(cursor)


class AsyncClient(Commands):
    def __init__(self, endpoint, token, *, timeout=30, transport=None):
        self._configure(endpoint, token, timeout)
        self.http = httpx2.AsyncClient(
            base_url=endpoint.rstrip("/"),
            timeout=timeout,
            trust_env=False,
            follow_redirects=False,
            transport=transport,
        )

    async def __aenter__(self):
        return self

    async def __aexit__(self, *args):
        await self.close()

    async def close(self):
        await self.http.aclose()

    async def _request(self, method, path, *, command=None, **kwargs):
        try:
            async with self.http.stream(
                method, api_path(path), headers=self._headers(), **kwargs
            ) as response:
                check_status(response)
                raw = bytearray()
                async for chunk in response.aiter_bytes():
                    raw.extend(chunk)
                    if len(raw) > 4194304:
                        raise ValueError("API response exceeded its bound.")
                return buffered(response, raw)
        except httpx2.HTTPError as exc:
            raise TransportError(command) from exc

    async def get(self, path):
        return (await self._request("GET", path)).json()

    async def execute(self, command):
        return (
            await self._request(
                "POST", command.path, command=command, json=command.body
            )
        ).json()

    async def submit(self, command):
        return Session.model_validate(await self.execute(command))

    async def create_session(self, agent_id, title="New conversation"):
        return await self.submit(self.create(agent_id, title))

    async def session(self, identifier):
        return Session.model_validate(
            await self.get("/v1/sessions/" + session_id(identifier))
        )

    async def agents(self):
        return (await self.get("/v1/agents"))["agents"]

    async def capabilities(self, agent_id):
        return await self.get(self._agent_path(agent_id))

    async def events(self, identifier, after=0):
        response = await self._request(
            "GET",
            "/v1/sessions/" + session_id(identifier) + "/events",
            params={"after": after},
        )
        return [Event.model_validate(value) for value in response.json()["events"]]

    async def download(self, identifier, path):
        valid_path(path)
        return (
            await self._request(
                "GET", f"/v1/sessions/{session_id(identifier)}/files/{path}"
            )
        ).content

    async def _snapshot(self, identifier, end, cursor=None):
        remaining = end - time.monotonic()
        if remaining <= 0:
            raise WaitTimeout(identifier, cursor)
        response = await self._request(
            "GET",
            "/v1/sessions/" + session_id(identifier),
            timeout=min(self.timeout, remaining),
        )
        return Session.model_validate(response.json())

    async def wait(self, identifier, *, timeout=300, poll_interval=0.5):  # noqa: ASYNC109 - SDK deadline also returns a resumable cursor.
        if not 0 < timeout <= 3600 or not 0 < poll_interval <= 10:
            raise ValueError("Use bounded wait options.")
        end = time.monotonic() + timeout
        while time.monotonic() < end:
            response = await self._request(
                "GET",
                "/v1/sessions/" + session_id(identifier),
                timeout=max(0.001, min(self.timeout, end - time.monotonic())),
            )
            row = Session.model_validate(response.json())
            if row.status not in ACTIVE:
                return row
            await asyncio.sleep(min(poll_interval, max(0, end - time.monotonic())))
        raise WaitTimeout(identifier)

    async def stream(
        self, identifier, *, after=0, reconnects=3, timeout=300, stop_on_pause=True
    ):  # noqa: ASYNC109 - public SDK deadline.
        self._stream_options(after, reconnects, timeout)
        cursor = after
        end = time.monotonic() + timeout
        pause_at = None
        if stop_on_pause:
            row = await self._snapshot(identifier, end, cursor)
            pause_at = row.revision if row.status not in ACTIVE else None
            if pause_at is not None and cursor >= pause_at:
                return
        for attempt in range(reconnects + 1):
            if time.monotonic() >= end:
                raise WaitTimeout(identifier, cursor)
            decoder = EventDecoder()
            try:
                async with self.http.stream(
                    "GET",
                    "/v1/sessions/" + session_id(identifier) + "/stream",
                    params={"after": cursor},
                    headers=self._headers(),
                    timeout=min(65, end - time.monotonic()),
                ) as response:
                    check_status(response)
                    if not response.headers.get("content-type", "").startswith(
                        "text/event-stream"
                    ):
                        raise ValueError("Expected an event stream.")
                    async for chunk in response.aiter_bytes():
                        if time.monotonic() >= end:
                            raise WaitTimeout(identifier, cursor)
                        for kind, data in decoder.feed(chunk):
                            if kind == "access.closed":
                                raise StreamClosed(
                                    cursor,
                                    "Access changed or expired; refresh credentials before resuming.",
                                )
                            event = Event.model_validate(data)
                            if kind != event.kind:
                                raise ValueError("Event type mismatch.")
                            if event.revision <= cursor:
                                continue
                            cursor = event.revision
                            yield event
                            if stop_on_pause and event.kind in PAUSE_EVENTS:
                                row = await self._snapshot(identifier, end, cursor)
                                pause_at = (
                                    row.revision if row.status not in ACTIVE else None
                                )
                            if pause_at is not None and cursor >= pause_at:
                                return
                    decoder.finish()
            except (httpx2.HTTPError, IncompleteStream):
                pass
            if stop_on_pause:
                row = await self._snapshot(identifier, end, cursor)
                if row.status not in ACTIVE and cursor >= row.revision:
                    return
            if attempt < reconnects:
                await asyncio.sleep(
                    min(0.1 * (attempt + 1), max(0, end - time.monotonic()))
                )
        raise StreamClosed(cursor)
